#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { buildSourceInventoryRows } from "../src/source-effectiveness.js";

const DEFAULT_OUT_PATH = "docs/source-inventory-order.md";

export function buildSourceInventoryOrderMarkdown({ rootDir = process.cwd() } = {}) {
  const rows = buildSourceInventoryRows({ rootDir });
  const groups = groupInventoryRows(rows);
  const generatedAt = "deterministic";
  const lines = [
    "# Source Inventory Order Reference",
    "",
    "<!-- source-inventory-order:v1 -->",
    "<!-- inventory-fixed-order-reference -->",
    "",
    "Status: `phase-8-order-reference`",
    "",
    "Maintenance owner: `user-reviewed-fixed-source-order`",
    "",
    "Generated by: `node scripts/generate-source-inventory-order.mjs`",
    "",
    `Snapshot: ${rows.length} registered collection entries, generated mode ${generatedAt}.`,
    "",
    "This reference is the static human review surface for the full collection-entry order used by the public `source-inventory-group-*` sections. It deliberately shows only source names, ids, logical-source mapping, source kind, enablement, tier, authority, platform, and generic configuration status.",
    "",
    "Internal source-first runtime may project a per-row runtime layer onto these entries: mapped entries inherit their logical source `status_label`, mapped-but-missing entries show `unreported`, and unmapped entries show `collection_only`. Public daily pages do not render this inventory by default. That runtime layer is intentionally omitted here so this file remains a fixed order reference.",
    "",
    "Daily source status must not reorder this reference. Blocked, unconfigured, manual, skipped, or no-update entries stay in their fixed section so source gaps remain visible.",
    "",
    "## Section Counts",
    "",
    "| Section | Entries | Logical mappings | Core | Optional | Manual |",
    "|---|---:|---:|---:|---:|---:|",
    ...groups.map((group) => sectionCountRow(group)),
    "",
    "## How To Tune The Order",
    "",
    "<!-- collection-entry-insertion-rules -->",
    "",
    "1. Decide whether a new collection entry belongs to an existing logical source. If it does, add the entry near that logical source's existing collection entries.",
    "2. If the entry is important enough to become a first-class logical source, update `config/source-display-contract.json` in the same PR and give it a stable section and rank.",
    "3. If it remains an unmapped collection entry, place it in the inferred fixed section and preserve deterministic registry order until the user promotes it.",
    "4. Do not use today's reachability, blocked status, candidate count, or public inclusion to move entries up or down.",
    "5. After adding or moving sources, regenerate this file and run the validation commands below.",
    "",
    "## Validation",
    "",
    "<!-- inventory-validation-commands -->",
    "",
    "```powershell",
    "node scripts/generate-source-inventory-order.mjs",
    "corepack pnpm run sources:display-contract",
    "corepack pnpm run validate",
    "```",
    "",
    "## Full Order",
    ""
  ];

  for (const group of groups) {
    lines.push(...sectionLines(group));
  }

  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

function groupInventoryRows(rows = []) {
  const groups = [];
  const bySection = new Map();
  for (const row of rows) {
    const sectionId = String(row.display_section || "uncategorized");
    if (!bySection.has(sectionId)) {
      const group = {
        id: sectionId,
        label: String(row.display_section_label || sectionId),
        rank: Number.isFinite(Number(row.display_section_rank)) ? Number(row.display_section_rank) : 999,
        rows: []
      };
      bySection.set(sectionId, group);
      groups.push(group);
    }
    bySection.get(sectionId).rows.push(row);
  }
  return groups.sort((left, right) => left.rank - right.rank || left.label.localeCompare(right.label));
}

function sectionCountRow(group) {
  const enablement = countBy(group.rows, "enablement");
  const logicalSources = new Set(group.rows.map((row) => row.logical_source_id).filter(Boolean));
  return `| \`${escapeTable(group.id)}\` ${escapeTable(group.label)} | ${group.rows.length} | ${logicalSources.size} | ${enablement.core || 0} | ${enablement.optional || 0} | ${enablement.manual || 0} |`;
}

function sectionLines(group) {
  return [
    `### ${escapeMarkdown(group.label)} (\`${escapeMarkdown(group.id)}\`)`,
    "",
    `<!-- inventory-section:${group.id} count:${group.rows.length} -->`,
    "",
    "| Order | Source ID | Name | Logical source | Kind | Enablement | Tier | Authority | Platform | Config status |",
    "|---:|---|---|---|---|---|---|---|---|---|",
    ...group.rows.map((row, index) => inventoryRow(group, row, index)),
    ""
  ];
}

function inventoryRow(group, row, index) {
  const order = `${String(group.rank).padStart(2, "0")}.${String(index + 1).padStart(3, "0")}`;
  return [
    `| ${order}`,
    codeCell(row.id),
    escapeTable(row.name || row.id),
    codeCell(row.logical_source_id || "unmapped"),
    codeCell(row.source_kind || "unknown"),
    codeCell(row.enablement || "unknown"),
    codeCell(row.tier || "-"),
    codeCell(row.authority || "-"),
    codeCell(row.platform || "-"),
    codeCell(row.config_status || "placeholder")
  ].join(" | ") + " |";
}

function countBy(rows = [], field) {
  const counts = {};
  for (const row of rows) {
    const key = String(row?.[field] || "unknown");
    counts[key] = (counts[key] || 0) + 1;
  }
  return counts;
}

function codeCell(value) {
  return `\`${escapeTable(value)}\``;
}

function escapeTable(value) {
  return String(value || "").replaceAll("|", "\\|").replace(/\s+/g, " ").trim();
}

function escapeMarkdown(value) {
  return String(value || "").replaceAll("[", "\\[").replaceAll("]", "\\]");
}

async function main() {
  const outPath = process.argv[2] || DEFAULT_OUT_PATH;
  const rootDir = process.cwd();
  const fullPath = path.resolve(rootDir, outPath);
  await fs.mkdir(path.dirname(fullPath), { recursive: true });
  await fs.writeFile(fullPath, buildSourceInventoryOrderMarkdown({ rootDir }), "utf8");
  process.stdout.write(`${path.relative(rootDir, fullPath).replace(/\\/g, "/")}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
